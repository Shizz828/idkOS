#!/usr/bin/env python3
"""Regenerate src/ui/BootLogo.h (RGB565) from data/boot/idkos-logo.png."""
import pathlib
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data/boot/idkos-logo.png"
OUTPUT = ROOT / "src/ui/BootLogo.h"
SCREEN_W, SCREEN_H = 240, 135
LOGO_H = 119   # on-screen logo height; leaves 8 px of black above and below
DARK = 40      # source pixels this dark are background, not artwork


def main():
    image = Image.open(SOURCE).convert("RGB")
    # Artwork bounds: the logo sits on near-black; the cloud's gray outline is the edge.
    mask = image.convert("L").point(lambda v: 255 if v > DARK else 0)
    image = image.crop(mask.getbbox())
    width = round(image.width * LOGO_H / image.height)
    logo = image.resize((width, LOGO_H), Image.LANCZOS)
    logo = logo.filter(ImageFilter.UnsharpMask(radius=1, percent=60, threshold=2))
    pixels = logo.load()
    for y in range(logo.height):
        for x in range(logo.width):
            if max(pixels[x, y]) < DARK:  # source background noise becomes true black
                pixels[x, y] = (0, 0, 0)
    logo.save(ROOT / ".pio/boot-logo-preview.png") if (ROOT / ".pio").is_dir() else None
    values = []
    for y in range(logo.height):
        for x in range(logo.width):
            r, g, b = pixels[x, y]
            values.append((r >> 3) << 11 | (g >> 2) << 5 | b >> 3)
    rows = [", ".join(f"0x{v:04X}" for v in values[i:i + 12]) for i in range(0, len(values), 12)]
    OUTPUT.write_text(
        "#pragma once\n#include <stdint.h>\n"
        "// Generated by scripts/make_boot_logo.py from data/boot/idkos-logo.png.\n"
        "// Native-order RGB565; push with swap bytes on (see presentStartupLogo).\n"
        "namespace spark {\n"
        f"constexpr int BootLogoX={(SCREEN_W - width) // 2},BootLogoY={(SCREEN_H - LOGO_H) // 2},"
        f"BootLogoW={width},BootLogoH={LOGO_H};\n"
        "static const uint16_t BootLogoPixels[]={\n" + ",\n".join(rows) + "\n};\n}\n")


if __name__ == "__main__":
    main()
